"""
Oracle 相容性測試（不需連線）：用 Oracle 方言編譯 SQL，檢查產生的語法。

背景：Oracle 的整數主鍵不會自動編號，必須宣告 IDENTITY，
否則 INSERT 時會出現 ORA-01400（cannot insert NULL into ID）。
"""
import pytest
from sqlalchemy import literal_column, select
from sqlalchemy.dialects import oracle
from sqlalchemy.schema import CreateTable

from app.models import Item, StockTransaction, User


@pytest.mark.parametrize("model", [User, Item, StockTransaction])
def test_primary_key_is_identity_on_oracle(model):
    ddl = str(CreateTable(model.__table__).compile(dialect=oracle.dialect()))
    assert "id INTEGER GENERATED BY DEFAULT AS IDENTITY" in ddl


def test_varchar_uses_char_semantics_on_oracle():
    # 長度以「字」計算（VARCHAR2(n CHAR)），中文一字 3 bytes 也不會超過欄位長度
    ddl = str(CreateTable(Item.__table__).compile(dialect=oracle.dialect()))
    assert "name VARCHAR2(100 CHAR)" in ddl


def test_health_query_adds_from_dual_on_oracle():
    # /health 用的查詢；Oracle 的 SELECT 必須有 FROM，SQLAlchemy 會自動補 DUAL
    sql = str(select(literal_column("1")).compile(dialect=oracle.dialect()))
    assert sql == "SELECT 1 FROM DUAL"
